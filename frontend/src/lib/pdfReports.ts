import { jsPDF } from 'jspdf';

export interface BudgetRow {
  id?: string;
  category: string;
  allocated_amount: number;
  remaining_amount: number;
  fiscal_year?: number | string;
}

export interface ExpenseRow {
  id?: string;
  title: string;
  amount: number;
  category?: string;
  program_title?: string;
  budget_category?: string;
  created_at?: string;
}

export interface PDFReportOptions {
  barangayName: string;
  fiscalYear: number | string;
  budgets: BudgetRow[];
  expenses: ExpenseRow[];
  chairperson?: string;
  generatedBy?: string;
}

const peso = (n: number) =>
  `PHP ${Number(n || 0).toLocaleString('en-PH', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;

function drawHeader(doc: jsPDF, title: string, opts: PDFReportOptions) {
  doc.setFillColor(21, 128, 61);
  doc.rect(0, 0, 210, 25, 'F');
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(14);
  doc.setFont('helvetica', 'bold');
  doc.text('KABISIG', 15, 12);
  doc.setFontSize(9);
  doc.setFont('helvetica', 'normal');
  doc.text('Kabataan Bagong Sistema para sa Inklusibong Gobyerno', 15, 18);
  doc.text(title, 195, 12, { align: 'right' });

  doc.setTextColor(0, 0, 0);
  doc.setFontSize(10);
  doc.setFont('helvetica', 'bold');
  doc.text(`Barangay: ${opts.barangayName}`, 15, 35);
  doc.setFont('helvetica', 'normal');
  doc.text(`Fiscal Year: ${opts.fiscalYear}`, 15, 41);
  doc.text(`Generated: ${new Date().toLocaleString('en-PH')}`, 15, 47);
  if (opts.chairperson) doc.text(`Prepared for: ${opts.chairperson}`, 120, 35);
  if (opts.generatedBy) doc.text(`Generated by: ${opts.generatedBy}`, 120, 41);
}

function drawFooter(doc: jsPDF) {
  const pages = doc.getNumberOfPages();
  for (let i = 1; i <= pages; i++) {
    doc.setPage(i);
    doc.setFontSize(8);
    doc.setFont('helvetica', 'italic');
    doc.setTextColor(120, 120, 120);
    doc.text(
      `COA-Ready Report - Generated by KABISIG | Page ${i} of ${pages}`,
      105, 290, { align: 'center' }
    );
  }
}

function drawTable(
  doc: jsPDF,
  startY: number,
  headers: string[],
  widths: number[],
  rows: string[][],
  align: ('left' | 'right')[] = []
): number {
  let y = startY;
  doc.setFontSize(9);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(21, 128, 61);
  let x = 15;
  headers.forEach((h, i) => {
    doc.text(h, x, y);
    x += widths[i];
  });
  y += 2;
  doc.setDrawColor(21, 128, 61);
  doc.setLineWidth(0.4);
  doc.line(15, y, 195, y);
  y += 5;

  doc.setTextColor(0, 0, 0);
  doc.setFont('helvetica', 'normal');
  doc.setLineWidth(0.1);
  rows.forEach((row, ri) => {
    if (y > 275) {
      doc.addPage();
      y = 20;
      doc.setFont('helvetica', 'bold');
      doc.setTextColor(21, 128, 61);
      x = 15;
      headers.forEach((h, i) => {
        doc.text(h, x, y);
        x += widths[i];
      });
      y += 5;
      doc.setTextColor(0, 0, 0);
      doc.setFont('helvetica', 'normal');
    }
    if (ri % 2 === 0) {
      doc.setFillColor(245, 247, 245);
      doc.rect(15, y - 3, 180, 5, 'F');
    }
    x = 15;
    row.forEach((cell, ci) => {
      const a = align[ci] || 'left';
      if (a === 'right') {
        doc.text(cell, x + widths[ci] - 2, y, { align: 'right' });
      } else {
        doc.text(cell, x, y);
      }
      x += widths[ci];
    });
    y += 5;
  });
  return y;
}

// ---- Report 1: Budget Utilization Report ----
export function generateBudgetUtilizationReport(opts: PDFReportOptions): void {
  const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' });
  drawHeader(doc, 'Budget Utilization Report', opts);

  const budgetRows = opts.budgets.map((b) => {
    const spent = Number(b.allocated_amount) - Number(b.remaining_amount);
    const util = Number(b.allocated_amount) > 0
      ? ((spent / Number(b.allocated_amount)) * 100).toFixed(1)
      : '0.0';
    return [
      String(b.category || '-').substring(0, 28),
      peso(b.allocated_amount),
      peso(spent),
      peso(b.remaining_amount),
      `${util}%`,
    ];
  });

  const totalAlloc = opts.budgets.reduce((s, b) => s + Number(b.allocated_amount || 0), 0);
  const totalRem = opts.budgets.reduce((s, b) => s + Number(b.remaining_amount || 0), 0);
  const totalSpent = totalAlloc - totalRem;
  const totalUtil = totalAlloc > 0 ? ((totalSpent / totalAlloc) * 100).toFixed(1) : '0.0';

  budgetRows.push(['TOTAL', peso(totalAlloc), peso(totalSpent), peso(totalRem), `${totalUtil}%`]);

  let y = drawTable(
    doc, 60,
    ['Category', 'Allocated', 'Spent', 'Remaining', 'Util %'],
    [65, 30, 30, 30, 25],
    budgetRows,
    ['left', 'right', 'right', 'right', 'right']
  );

  y += 15;
  doc.setFontSize(11);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(21, 128, 61);
  doc.text('Expense Details', 15, y);
  y += 7;

  if (opts.expenses.length === 0) {
    doc.setFontSize(9);
    doc.setFont('helvetica', 'italic');
    doc.setTextColor(120, 120, 120);
    doc.text('No expenses recorded for this fiscal year.', 15, y);
  } else {
    drawTable(
      doc, y,
      ['Expense', 'Program', 'Category', 'Amount', 'Date'],
      [55, 40, 30, 30, 25],
      opts.expenses.map((e) => [
        String(e.title || '-').substring(0, 32),
        String(e.program_title || 'General').substring(0, 22),
        String(e.budget_category || e.category || '-').substring(0, 16),
        peso(e.amount),
        e.created_at ? new Date(e.created_at).toLocaleDateString('en-PH') : '-',
      ]),
      ['left', 'left', 'left', 'right', 'right']
    );
  }

  drawFooter(doc);
  const safeName = String(opts.barangayName || 'Barangay').replace(/\s+/g, '_');
  const stamp = new Date().toISOString().split('T')[0];
  doc.save(`KABISIG_Budget_Report_${safeName}_${opts.fiscalYear}_${stamp}.pdf`);
}

// ---- Report 2: Attendance Sheet ----
export function generateAttendanceSheet(options: {
  barangayName: string;
  programTitle: string;
  programDate: string;
  participants: Array<{ name: string; digital_id?: string; checked_in_at?: string; status?: string }>;
  generatedBy?: string;
}): void {
  const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' });

  doc.setFillColor(21, 128, 61);
  doc.rect(0, 0, 210, 22, 'F');
  doc.setTextColor(255, 255, 255);
  doc.setFontSize(14);
  doc.setFont('helvetica', 'bold');
  doc.text('KABISIG', 15, 12);
  doc.setFontSize(9);
  doc.setFont('helvetica', 'normal');
  doc.text('Attendance Sheet', 195, 12, { align: 'right' });

  doc.setTextColor(0, 0, 0);
  doc.setFontSize(10);
  doc.setFont('helvetica', 'bold');
  doc.text(`Program: ${options.programTitle}`, 15, 32);
  doc.setFont('helvetica', 'normal');
  doc.text(`Barangay: ${options.barangayName}`, 15, 38);
  doc.text(`Date: ${options.programDate}`, 15, 44);
  doc.text(`Generated: ${new Date().toLocaleString('en-PH')}`, 15, 50);
  if (options.generatedBy) doc.text(`Generated by: ${options.generatedBy}`, 15, 56);

  const rows = options.participants.map((p, i) => [
    String(i + 1),
    String(p.name || '-').substring(0, 35),
    String(p.digital_id || '-').substring(0, 18),
    p.checked_in_at ? new Date(p.checked_in_at).toLocaleString('en-PH') : '-',
    String(p.status || '-'),
  ]);

  drawTable(
    doc, 65,
    ['#', 'Full Name', 'Digital ID', 'Check-In Time', 'Status'],
    [10, 70, 40, 40, 20],
    rows,
    ['left', 'left', 'left', 'left', 'left']
  );

  drawFooter(doc);
  const safeName = String(options.barangayName || 'Barangay').replace(/\s+/g, '_');
  const safeProg = String(options.programTitle || 'Program').replace(/\s+/g, '_').substring(0, 30);
  doc.save(`KABISIG_Attendance_${safeName}_${safeProg}.pdf`);
}

